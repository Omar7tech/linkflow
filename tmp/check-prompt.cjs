const { chromium }=require('playwright-core');
const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://localhost:3000/tools/prompt-workbench');
await page.getByRole('textbox',{name:'Your thoughts',exact:true}).waitFor();
await page.waitForTimeout(1000);
assert.equal(await page.locator('footer').count(),0);
assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight),900);
await page.screenshot({path:'tmp/prompt-empty.png'});
await page.getByRole('textbox',{name:'Your thoughts',exact:true}).fill('Create a landing page for my studio. My audience is homeowners. The page must include projects and a contact form. The page must include projects and a contact form. Return a responsive implementation. Avoid autoplay animations.');
await page.getByRole('button',{name:'Organize my thoughts'}).click();
await page.getByRole('textbox',{name:'Goal idea',exact:true}).waitFor();
const prompt=await page.getByLabel('Assembled prompt').innerText();
assert.match(prompt,/landing page/);assert.match(prompt,/contact form/);assert.match(prompt,/responsive/);
await page.getByRole('button',{name:'Suggestions'}).click();
await page.getByRole('button',{name:'Set repeat aside'}).click();
await page.keyboard.press('Escape');
assert.equal((await page.getByLabel('Assembled prompt').innerText()).match(/contact form/g).length,1);
await page.getByRole('button',{name:'Undo edit'}).click();
assert.equal((await page.getByLabel('Assembled prompt').innerText()).match(/contact form/g).length,2);
await page.getByRole('button',{name:'Redo edit'}).click();
await page.locator('summary').filter({hasText:'Examples & references'}).click();
await page.getByRole('textbox',{name:'Add Examples & references',exact:true}).pressSequentially('A calm gallery website',{delay:10});
assert.equal(await page.getByRole('textbox',{name:'Examples & references idea',exact:true}).inputValue(),'A calm gallery website');
await page.screenshot({path:'tmp/prompt-filled.png'});
await page.waitForTimeout(600);await page.reload();
await page.getByRole('button',{name:'Structured brief',exact:true}).click();
assert.match(await page.getByLabel('Assembled prompt').innerText(),/calm gallery website/);
await page.setViewportSize({width:375,height:812});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth)<=375);
assert.equal(await page.evaluate(()=>document.documentElement.scrollHeight),812);
await page.getByRole('button',{name:'Your prompt',exact:true}).click();
assert.equal(await page.getByRole('button',{name:'Copy prompt',exact:true}).isVisible(),true);
await page.screenshot({path:'tmp/prompt-mobile.png'});
await page.getByRole('button',{name:'More options'}).click();await page.getByRole('menuitem',{name:'Version history'}).click();
await page.getByRole('textbox',{name:'Version name'}).fill('First version');await page.getByRole('button',{name:'Save',exact:true}).click();
await page.getByRole('button',{name:'Restore',exact:true}).waitFor();await page.keyboard.press('Escape');
await page.getByRole('link',{name:'Back to tools'}).click();await page.locator('footer').waitFor();
assert.equal(errors.length,0,errors.join('\n'));console.log('PASS full-screen, one-click organization, repetition, undo/redo, focus, persistence, mobile, versions, site navigation');
await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
